def add_xp(user, amount):
    if 'xp' not in user: user['xp'] = 0
    if 'level' not in user: user['level'] = 1
    user['xp'] += amount
    while user['xp'] >= user['level'] * 100:
        user['xp'] -= user['level'] * 100
        user['level'] += 1
        user['coins'] += 50

